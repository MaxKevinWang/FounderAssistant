"""Build benchmark question-set candidates from crawled FAQ datasets.

Design intent:
1) Convert structured FAQ Q/A records into True/False candidate statements.
2) Inject lightweight perturbations to generate negative (FALSE) items.
3) Emit runner-compatible JSON (`true_false` + `scenario`) plus markdown review.
4) Support holdout-aware filtering via deterministic split files.
"""

from __future__ import annotations

import json
import csv
import random
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from django.conf import settings

from apps.advisors.rag_pipeline import RAGError

ALLOWED_DECISION_DOMAINS = ("legal_form_selection", "funding_preparation", "market_validation")
SPLIT_SUBSETS = ("all", "train", "dev", "test")

SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+(?=[A-ZÄÖÜ0-9])|\n+")
DIGIT_RE = re.compile(r"\b\d{1,6}\b")
NOISE_PATTERNS = (
    "quelle",
    "telefon",
    "hotline",
    "www.",
    "http://",
    "https://",
    "impressum",
)
MODAL_HINTS = (
    "muss",
    "müssen",
    "kann",
    "können",
    "darf",
    "dürfen",
    "soll",
    "sollen",
    "ist",
    "sind",
    "wird",
    "werden",
)
PERTURBATION_MAP = (
    (r"\bkann\b", "muss"),
    (r"\bkönnen\b", "müssen"),
    (r"\bdarf\b", "muss"),
    (r"\bdürfen\b", "müssen"),
    (r"\bin der regel\b", "immer"),
    (r"\bmeist\b", "immer"),
    (r"\bgrundsätzlich\b", "ausschließlich"),
    (r"\büblicherweise\b", "ohne Ausnahme"),
)
ABBREVIATION_PATTERNS = (
    "z.B.",
    "u.a.",
    "bzw.",
    "d.h.",
    "Abs.",
    "Nr.",
    "Pkt.",
)


