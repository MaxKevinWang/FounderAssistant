    false_ratio: float
    seed: int
    decision_domains: tuple[str, ...]
    min_stand_year: int | None
    max_stand_year: int | None
    min_answer_chars: int
    review_csv_path: Path | None
    review_min_risk: int
    review_high_only: bool


