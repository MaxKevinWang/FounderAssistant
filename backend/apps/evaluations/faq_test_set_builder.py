def _load_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise RAGError(f"File not found: {path}")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise RAGError(f"Invalid JSON file {path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise RAGError(f"Expected JSON object in {path}.")
    return payload


def _write_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def _normalize_text(value: str) -> str:
    text = value.replace("\r", "\n")
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _protect_abbreviations(text: str) -> tuple[str, dict[str, str]]:
    """Protect frequent abbreviations to avoid sentence split artifacts."""

    protected = text
    token_map: dict[str, str] = {}
    for index, abbr in enumerate(ABBREVIATION_PATTERNS, start=1):
        token = f"__ABBR_{index}__"
        if abbr in protected:
            protected = protected.replace(abbr, token)
            token_map[token] = abbr
    return protected, token_map


def _restore_abbreviations(text: str, token_map: dict[str, str]) -> str:
    restored = text
    for token, abbr in token_map.items():
        restored = restored.replace(token, abbr)
    return restored


def _extract_year(stand_value: str) -> int | None:
    match = re.search(r"\b(19|20)\d{2}\b", stand_value)
    if not match:
        return None
    try:
        return int(match.group(0))
    except ValueError:
        return None


def _within_year_range(year: int | None, min_year: int | None, max_year: int | None) -> bool:
    if min_year is None and max_year is None:
        return True
    if year is None:
        return False
    if min_year is not None and year < min_year:
        return False
    if max_year is not None and year > max_year:
        return False
    return True


def _sentence_score(sentence: str) -> int:
    score = 0
    lower = sentence.lower()
    if any(marker in lower for marker in MODAL_HINTS):
        score += 3
    if DIGIT_RE.search(sentence):
        score += 2
    length = len(sentence)
    if 70 <= length <= 220:
        score += 2
    elif 40 <= length < 70:
        score += 1
    if any(marker in lower for marker in NOISE_PATTERNS):
        score -= 8
    if sentence.count(",") >= 2:
        score += 1
    return score


def _extract_candidate_sentence(answer_text: str) -> str | None:
    text = _normalize_text(answer_text)
    if not text:
        return None
    protected_text, token_map = _protect_abbreviations(text)
    sentences = []
    for chunk in SENTENCE_SPLIT_RE.split(protected_text):
        sentence = _restore_abbreviations(chunk, token_map).strip(" -•\t")
        if not sentence:
            continue
        if len(sentence) < 35 or len(sentence) > 320:
            continue
        lower = sentence.lower()
        if lower.startswith(("zu frage", "frage ", "quelle", "stand:")):
            continue
        if sentence.count("(") != sentence.count(")"):
            continue
        if sentence.count('"') % 2 != 0:
            continue
        if len(sentence.split()) < 8:
            continue
        sentences.append(sentence)
    if not sentences:
        return None
    ranked = sorted(sentences, key=lambda item: (_sentence_score(item), len(item)), reverse=True)
    return ranked[0] if ranked else None


def _ensure_sentence_end(sentence: str) -> str:
    trimmed = sentence.strip()
    if trimmed.endswith((".", "!", "?")):
        return trimmed
    return f"{trimmed}."


def _replace_first_number(sentence: str) -> tuple[str, str] | None:
    for match in DIGIT_RE.finditer(sentence):
        context_left = sentence[max(0, match.start() - 18) : match.start()].lower()
        if any(marker in context_left for marker in ("frage", "§", "art", "abs", "nr", "pkt")):
            continue
        original = match.group(0)
        try:
            old_value = int(original)
        except ValueError:
            continue
        new_value = old_value + 1 if old_value < 1000 else max(1, old_value - 1)
        replaced = sentence[: match.start()] + str(new_value) + sentence[match.end() :]
        if replaced != sentence:
            return replaced, "numeric_shift"
    return None


def _remove_first_negation(sentence: str) -> tuple[str, str] | None:
    replaced = re.sub(r"\bnicht\b\s*", "", sentence, count=1, flags=re.IGNORECASE)
    if replaced != sentence:
        return replaced, "negation_removed"
    return None


def _replace_modal_or_quantifier(sentence: str) -> tuple[str, str] | None:
    for pattern, replacement in PERTURBATION_MAP:
        replaced = re.sub(pattern, replacement, sentence, count=1, flags=re.IGNORECASE)
        if replaced != sentence:
            return replaced, f"keyword_swap:{pattern}->{replacement}"
    return None


def _insert_negation(sentence: str) -> tuple[str, str] | None:
    replaced = re.sub(
        r"\b(kann|können|muss|müssen|darf|dürfen|ist|sind|wird|werden)\b",
        r"\1 nicht",
        sentence,
        count=1,
        flags=re.IGNORECASE,
    )
    if replaced != sentence:
        return replaced, "negation_inserted"
    return None


def _build_false_sentence(sentence: str) -> tuple[str, str]:
    """Generate a likely-false perturbation from a source sentence."""

    for strategy in (_replace_first_number, _remove_first_negation, _replace_modal_or_quantifier, _insert_negation):
        result = strategy(sentence)
        if result is not None:
            perturbed, method = result
            return _ensure_sentence_end(_normalize_text(perturbed)), method
    fallback = f"{_ensure_sentence_end(sentence)} Dies gilt immer und ohne Ausnahme."
    return _normalize_text(fallback), "absolute_generalization"


def _clean_sentence(sentence: str) -> str:
    """Normalize sentence prefix artifacts from FAQ prose snippets."""

    cleaned = sentence.strip()
    cleaned = re.sub(r"^(D\.h\.|d\.h\.|Das heißt)\s*", "", cleaned)
    cleaned = cleaned.strip()
    return _ensure_sentence_end(cleaned)


def _build_statement(title: str, sentence: str) -> str:
    return f"Laut der BMWE-FAQ-Antwort zum Thema \"{title}\" gilt: {_clean_sentence(sentence)}"


def _load_split_ids(split_json_path: Path, split_subset: str) -> set[str]:
    if split_subset == "all":
        return set()
    payload = _load_json(split_json_path)
    splits = payload.get("splits", {})
    if not isinstance(splits, dict):
        raise RAGError(f"Invalid split format in {split_json_path}: missing 'splits' object.")
    values = splits.get(split_subset, [])
    if not isinstance(values, list):
        raise RAGError(f"Invalid split format in {split_json_path}: split '{split_subset}' must be a list.")
    return {str(item) for item in values}


def _filter_faq_items(config: FAQTestSetBuildConfig) -> list[dict[str, Any]]:
    dataset = _load_json(config.faq_dataset_path)
    items = dataset.get("items", [])
    if not isinstance(items, list):
        raise RAGError(f"Invalid FAQ dataset format in {config.faq_dataset_path}: 'items' must be a list.")

    split_ids: set[str] = set()
    if config.split_subset != "all":
        if config.split_json_path is None:
            raise RAGError("split_subset is not 'all' but split_json_path is missing.")
        split_ids = _load_split_ids(config.split_json_path, config.split_subset)

    selected: list[dict[str, Any]] = []
    allowed_domains = set(config.decision_domains)
    for item in items:
        faq_id = str(item.get("id", ""))
        if not faq_id:
            continue
        if split_ids and faq_id not in split_ids:
            continue
        domain = str(item.get("decision_domain", ""))
        if domain not in allowed_domains:
            continue
        answer = _normalize_text(str(item.get("reference_answer", "")))
        if len(answer) < config.min_answer_chars:
            continue
        stand_year = item.get("stand_year")
        if stand_year is None:
            stand_year = _extract_year(str(item.get("stand", "")))
        elif isinstance(stand_year, str):
            try:
                stand_year = int(stand_year.strip())
            except ValueError:
                stand_year = _extract_year(str(item.get("stand", "")))
        if not _within_year_range(
            year=int(stand_year) if isinstance(stand_year, int) else None,
            min_year=config.min_stand_year,
            max_year=config.max_stand_year,
        ):
            continue
        selected.append(item)
    return selected


def _balanced_pick(pool: list[dict[str, Any]], target_count: int, seed: int) -> list[dict[str, Any]]:
    if target_count <= 0 or not pool:
        return []
    grouped: dict[str, list[dict[str, Any]]] = {}
    for item in pool:
        grouped.setdefault(str(item.get("domain", "")), []).append(item)
    rnd = random.Random(seed)
    for values in grouped.values():
        rnd.shuffle(values)

    domain_order = sorted(grouped.keys())
    picked: list[dict[str, Any]] = []
    while len(picked) < target_count:
        progressed = False
        for domain in domain_order:
            bucket = grouped.get(domain, [])
            if not bucket:
                continue
            picked.append(bucket.pop())
            progressed = True
            if len(picked) >= target_count:
                break
        if not progressed:
            break
    return picked


def _build_tf_pool(faq_items: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    true_pool: list[dict[str, Any]] = []
    false_pool: list[dict[str, Any]] = []
    for item in faq_items:
        title = str(item.get("title", "")).strip() or "FAQ entry"
        answer = str(item.get("reference_answer", ""))
        sentence = _extract_candidate_sentence(answer)
        if sentence is None:
            continue
        domain = str(item.get("decision_domain", ""))
        source_url = str(item.get("source_url", ""))
        stand = str(item.get("stand", ""))
        stand_year = item.get("stand_year")
        true_statement = _build_statement(title=title, sentence=sentence)
        true_pool.append(
            {
                "domain": domain,
                "statement": true_statement,
                "gold_label": "TRUE",
                "source": source_url,
                "source_url": source_url,
                "source_faq_id": item.get("id", ""),
                "source_title": title,
                "stand": stand,
                "stand_year": stand_year,
                "generation_method": "faq_sentence_true",
                "perturbation_type": "",
            }
        )

        false_sentence, perturbation_type = _build_false_sentence(sentence)
        false_statement = _build_statement(title=title, sentence=false_sentence)
        false_pool.append(
            {
                "domain": domain,
                "statement": false_statement,
                "gold_label": "FALSE",
                "source": source_url,
                "source_url": source_url,
                "source_faq_id": item.get("id", ""),
                "source_title": title,
                "stand": stand,
                "stand_year": stand_year,
                "generation_method": "faq_sentence_false",
                "perturbation_type": perturbation_type,
            }
        )
    return true_pool, false_pool


def _count_by_domain(items: list[dict[str, Any]]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for item in items:
        domain = str(item.get("domain", ""))
        counts[domain] = counts.get(domain, 0) + 1
    return counts


def _compute_risk(item: dict[str, Any]) -> tuple[int, list[str]]:
    """Compute manual-review risk score for one TF candidate."""

    score = 0
    reasons: list[str] = []
    domain = str(item.get("domain", ""))
    perturbation = str(item.get("perturbation_type", ""))
    statement = str(item.get("statement", ""))
    stand_year = item.get("stand_year")

    if domain == "legal_form_selection":
        score += 1
        reasons.append("legal_domain")

    if stand_year in (None, ""):
        score += 2
        reasons.append("missing_stand_year")

    if perturbation == "numeric_shift":
        score += 2
        reasons.append("numeric_perturbation")
    elif perturbation == "negation_removed":
        score += 3
        reasons.append("negation_removed")
    elif perturbation.startswith("keyword_swap:"):
        score += 2
        reasons.append("keyword_swap")
    elif perturbation == "absolute_generalization":
        score += 1
        reasons.append("absolute_generalization")

    length = len(statement)
    if length < 90:
        score += 1
        reasons.append("short_statement")
    elif length > 300:
        score += 2
        reasons.append("long_statement")

    if statement.count("(") != statement.count(")"):
        score += 2
        reasons.append("unbalanced_parentheses")
    if statement.count('"') % 2 != 0:
        score += 2
        reasons.append("unbalanced_quotes")

    if "D.h." in statement or "d.h." in statement:
        score += 1
        reasons.append("abbreviation_prefix")

    return score, reasons


def _priority_from_score(score: int) -> str:
    if score >= 6:
        return "HIGH"
    if score >= 3:
        return "MEDIUM"
    return "LOW"


def _build_review_rows(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for item in items:
        score, reasons = _compute_risk(item)
        priority = _priority_from_score(score)
        item["risk_score"] = score
        item["review_priority"] = priority
        item["review_reasons"] = reasons
        rows.append(
            {
                "tf_id": str(item.get("id", "")),
                "review_priority": priority,
                "risk_score": score,
                "risk_reasons": ";".join(reasons),
                "domain": str(item.get("domain", "")),
                "gold_label": str(item.get("gold_label", "")),
                "perturbation_type": str(item.get("perturbation_type", "")),
                "source_faq_id": str(item.get("source_faq_id", "")),
                "source_title": str(item.get("source_title", "")),
                "stand_year": str(item.get("stand_year", "")),
                "statement": str(item.get("statement", "")),
                "source_url": str(item.get("source", "")),
                "review_status": "TODO",
                "review_notes": "",
            }
        )
    rows.sort(key=lambda row: (int(row["risk_score"]), str(row["tf_id"])), reverse=True)
    for index, row in enumerate(rows, start=1):
        row["review_rank"] = index
    return rows


def _write_review_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "review_rank",
        "tf_id",
        "review_priority",
        "risk_score",
        "risk_reasons",
        "domain",
        "gold_label",
        "perturbation_type",
        "source_faq_id",
        "source_title",
        "stand_year",
        "statement",
        "source_url",
        "review_status",
        "review_notes",
    ]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _build_scenarios(faq_items: list[dict[str, Any]], seed: int) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    rnd = random.Random(seed)
    by_domain: dict[str, list[dict[str, Any]]] = {key: [] for key in ALLOWED_DECISION_DOMAINS}
    for item in faq_items:
        domain = str(item.get("decision_domain", ""))
        if domain in by_domain:
            by_domain[domain].append(item)

    for values in by_domain.values():
        values.sort(key=lambda row: (int(row.get("stand_year") or 0), str(row.get("id", ""))), reverse=True)

    def _sample_titles(domain: str, k: int) -> list[str]:
        items_for_domain = by_domain.get(domain, [])
        if not items_for_domain:
            return []
        return [str(item.get("title", "")) for item in items_for_domain[:k]]

    def _fallback_topics(existing: list[str], all_titles: list[str], default_label: str, k: int) -> list[str]:
        values = [topic for topic in existing if topic]
        for title in all_titles:
            if title and title not in values:
                values.append(title)
            if len(values) >= k:
                break
        while len(values) < k:
            values.append(default_label)
        return values[:k]

    legal_titles = _sample_titles("legal_form_selection", 2)
    funding_titles = _sample_titles("funding_preparation", 2)
    market_titles = _sample_titles("market_validation", 2)
    all_titles = [str(item.get("title", "")) for item in faq_items if str(item.get("title", "")).strip()]
    legal_titles = _fallback_topics(legal_titles, all_titles, "legal form and registration sequencing", 2)
    funding_titles = _fallback_topics(funding_titles, all_titles, "funding preparation and financing eligibility", 2)
    market_titles = _fallback_topics(market_titles, all_titles, "market entry and customer-compliance execution", 2)

    cross_topics = [*legal_titles[:1], *funding_titles[:1], *market_titles[:1]]
    rnd.shuffle(cross_topics)
    while len(cross_topics) < 3:
        cross_topics.append("regulatory and market-entry compliance questions")

    primary_prompt = (
        "A startup team in Germany is preparing to launch a digital B2C service within 10 weeks. "
        "They reviewed BMWE FAQ materials and still need actionable guidance.\n"
        f"Key open topics: (1) {cross_topics[0]}, (2) {cross_topics[1]}, (3) {cross_topics[2]}.\n"
        "Provide: (1) legal and registration recommendations for next 6-12 months, "
        "(2) funding preparation checklist and risk notes, "
        "(3) market-validation experiment plan with measurable thresholds, "
        "(4) a prioritized 30-day execution plan, and "
        "(5) at least 4 citations."
    )
    primary = {
        "id": "SC-FAQ-01",
        "domain": "cross_domain",
        "title": "Cross-domain founder scenario from BMWE FAQ corpus",
        "prompt": primary_prompt,
    }

    user_scenarios: list[dict[str, Any]] = []
    domain_to_topic = {
        "legal_form_selection": legal_titles,
        "funding_preparation": funding_titles,
        "market_validation": market_titles,
    }
    for index, domain in enumerate(ALLOWED_DECISION_DOMAINS, start=2):
        topics = domain_to_topic[domain]
        prompt = (
            "A founder in Germany is preparing a launch decision and asks for evidence-grounded guidance.\n"
            f"Focus topics: (1) {topics[0]}, (2) {topics[min(1, len(topics) - 1)]}.\n"
            "Please provide: (1) recommendation options with trade-offs, "
            "(2) compliance and process checklist, (3) near-term milestones, and (4) citations."
        )
        user_scenarios.append(
            {
                "id": f"SC-FAQ-{index:02d}",
                "domain": domain,
                "title": f"{domain} scenario from BMWE FAQ corpus",
                "prompt": prompt,
            }
        )
    return primary, user_scenarios


def _build_markdown(test_set: dict[str, Any]) -> str:
    metadata = test_set.get("metadata", {})
    tf_items = test_set.get("true_false", [])
    domain_counts = _count_by_domain(tf_items)
    priority_counts: dict[str, int] = {}
    for item in tf_items:
        priority = str(item.get("review_priority", ""))
        if priority:
            priority_counts[priority] = priority_counts.get(priority, 0) + 1

    lines = [
        "# FAQ-Derived Test Set Candidates",
        "",
        f"- Generated at (UTC): {metadata.get('generated_at_utc', '')}",
        f"- Source FAQ dataset: `{metadata.get('source_faq_dataset', '')}`",
        f"- Split subset: `{metadata.get('split_subset', '')}`",
        f"- TF candidate count: {len(tf_items)}",
        f"- Seed: {metadata.get('seed', '')}",
        "",
        "## Domain Distribution",
        "",
    ]
    for domain in sorted(domain_counts.keys()):
        lines.append(f"- `{domain}`: {domain_counts[domain]}")

    if priority_counts:
        lines.extend(["", "## Review Priority Distribution", ""])
        for key in ("HIGH", "MEDIUM", "LOW"):
            if key in priority_counts:
                lines.append(f"- `{key}`: {priority_counts[key]}")

    lines.extend(
        [
            "",
            "## TF Candidates (Preview)",
            "",
            "| ID | Domain | Label | Priority | Risk | Statement | Perturbation |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
    )
    for item in tf_items[:80]:
        statement = str(item.get("statement", "")).replace("|", "\\|")
        lines.append(
            f"| {item.get('id', '')} | {item.get('domain', '')} | {item.get('gold_label', '')} | "
            f"{item.get('review_priority', '')} | {item.get('risk_score', '')} | "
            f"{statement} | {item.get('perturbation_type', '')} |"
        )

    lines.extend(
        [
            "",
            "## Anti-Coupling Notes",
            "",
            "1. Use holdout subset (`split_subset=test`) for final reporting.",
            "2. Mix TRUE/FALSE through perturbation-based negatives.",
            "3. Keep manual review before locking the final thesis benchmark.",
        ]
    )
    return "\n".join(lines) + "\n"


def build_test_set_from_faq(config: FAQTestSetBuildConfig) -> dict[str, Any]:
    """Generate a benchmark-compatible test set from FAQ dataset records."""

    if config.tf_count <= 0:
        raise RAGError("tf_count must be > 0.")
    if not (0.0 <= config.false_ratio <= 1.0):
        raise RAGError("false_ratio must be within [0, 1].")
    if config.split_subset not in SPLIT_SUBSETS:
        raise RAGError(f"split_subset must be one of: {', '.join(SPLIT_SUBSETS)}")
    if not config.decision_domains:
        raise RAGError("decision_domains must not be empty.")
    for domain in config.decision_domains:
        if domain not in ALLOWED_DECISION_DOMAINS:
            raise RAGError(f"Invalid decision domain: {domain}")
    if (
        config.min_stand_year is not None
        and config.max_stand_year is not None
        and config.min_stand_year > config.max_stand_year
    ):
        raise RAGError("min_stand_year must be <= max_stand_year.")
    if config.review_min_risk < 0:
        raise RAGError("review_min_risk must be >= 0.")

    faq_items = _filter_faq_items(config)
    if not faq_items:
        raise RAGError("No FAQ items available after filters. Relax filters or verify input files.")

    true_pool, false_pool = _build_tf_pool(faq_items)
    if not true_pool:
        raise RAGError("No TF candidates could be generated from selected FAQ items.")

    target_false = min(int(round(config.tf_count * config.false_ratio)), len(false_pool))
    target_true = min(config.tf_count - target_false, len(true_pool))

    selected_true = _balanced_pick(true_pool, target_true, seed=config.seed + 11)
    selected_false = _balanced_pick(false_pool, target_false, seed=config.seed + 23)
    selected = selected_true + selected_false

    if len(selected) < config.tf_count:
        remainder = [*true_pool, *false_pool]
        picked_keys = {
            (str(item.get("source_faq_id", "")), str(item.get("gold_label", "")), str(item.get("statement", "")))
            for item in selected
        }
        for item in remainder:
            key = (str(item.get("source_faq_id", "")), str(item.get("gold_label", "")), str(item.get("statement", "")))
            if key in picked_keys:
                continue
            selected.append(item)
            picked_keys.add(key)
            if len(selected) >= config.tf_count:
                break

    rnd = random.Random(config.seed + 101)
    rnd.shuffle(selected)
    selected = selected[: config.tf_count]

    true_count = sum(1 for item in selected if item.get("gold_label") == "TRUE")
    false_count = sum(1 for item in selected if item.get("gold_label") == "FALSE")

    tf_items: list[dict[str, Any]] = []
    for index, item in enumerate(selected, start=1):
        tf_items.append(
            {
                "id": f"TF-FAQ-{index:03d}",
                "domain": item.get("domain", ""),
                "statement": item.get("statement", ""),
                "gold_label": item.get("gold_label", ""),
                "source": item.get("source", ""),
                "source_faq_id": item.get("source_faq_id", ""),
                "source_title": item.get("source_title", ""),
                "stand": item.get("stand", ""),
                "stand_year": item.get("stand_year"),
                "generation_method": item.get("generation_method", ""),
                "perturbation_type": item.get("perturbation_type", ""),
                "validation_status": "needs_manual_review",
            }
        )

    review_rows = _build_review_rows(tf_items)
    filtered_review_rows = [
        row
        for row in review_rows
        if int(row["risk_score"]) >= config.review_min_risk
        and (not config.review_high_only or row["review_priority"] == "HIGH")
    ]

    primary_scenario, user_scenarios = _build_scenarios(faq_items, seed=config.seed + 211)

    metadata = {
        "name": "faq_generated_test_set_candidates",
        "version": "1.0",
        "jurisdiction": "Germany",
        "generated_at_utc": datetime.now(UTC).isoformat(),
        "source_faq_dataset": str(config.faq_dataset_path),
        "source_split_json": str(config.split_json_path) if config.split_json_path else "",
        "split_subset": config.split_subset,
        "seed": config.seed,
        "tf_target_count": config.tf_count,
        "tf_generated_count": len(tf_items),
        "true_count": true_count,
        "false_count": false_count,
        "decision_domains": list(config.decision_domains),
        "min_stand_year": config.min_stand_year,
        "max_stand_year": config.max_stand_year,
        "min_answer_chars": config.min_answer_chars,
        "review_min_risk": config.review_min_risk,
        "review_high_only": config.review_high_only,
        "review_row_count": len(filtered_review_rows),
        "notes": (
            "Automatically generated candidate set from BMWE FAQ corpus. "
            "Manual legal validation is required before final thesis reporting."
        ),
    }

    payload = {
        "metadata": metadata,
        "true_false": tf_items,
        "scenario": primary_scenario,
        "user_scenarios": user_scenarios,
    }

    _write_json(config.output_json_path, payload)
    config.output_markdown_path.parent.mkdir(parents=True, exist_ok=True)
    config.output_markdown_path.write_text(_build_markdown(payload), encoding="utf-8")
    if config.review_csv_path is not None:
        _write_review_csv(config.review_csv_path, filtered_review_rows)

    return {
        "status": "ok",
        "output_json_path": str(config.output_json_path),
        "output_markdown_path": str(config.output_markdown_path),
        "review_csv_path": str(config.review_csv_path) if config.review_csv_path else "",
        "review_row_count": len(filtered_review_rows),
        "faq_items_after_filter": len(faq_items),
        "tf_generated_count": len(tf_items),
        "true_count": true_count,
        "false_count": false_count,
        "domain_distribution": _count_by_domain(tf_items),
    }
