"""Generate benchmark question-set candidates from FAQ dataset files."""

from __future__ import annotations

from pathlib import Path

from django.core.management.base import BaseCommand, CommandError

from apps.advisors.rag_pipeline import RAGError
from apps.evaluations.faq_test_set_builder import (
    ALLOWED_DECISION_DOMAINS,
    FAQTestSetBuildConfig,
    SPLIT_SUBSETS,
    build_test_set_from_faq,
    default_faq_dataset_path,
    default_output_json_path,
    default_output_markdown_path,
    default_review_csv_path,
    default_split_json_path,
)


class Command(BaseCommand):
    """CLI wrapper for FAQ-derived test-set candidate generation."""

    help = "Build True/False + scenario benchmark candidates from FAQ dataset."

    def add_arguments(self, parser):
        parser.add_argument("--faq-dataset", type=str, default=str(default_faq_dataset_path()))
        parser.add_argument(
            "--split-json",
            type=str,
            default=str(default_split_json_path()),
            help="Split file generated by FAQ crawler (used when split-subset != all).",
        )
        parser.add_argument("--split-subset", type=str, choices=list(SPLIT_SUBSETS), default="all")
        parser.add_argument("--output-json", type=str, default=str(default_output_json_path()))
        parser.add_argument("--output-md", type=str, default=str(default_output_markdown_path()))
        parser.add_argument("--review-csv", type=str, default=str(default_review_csv_path()))
        parser.add_argument("--no-review-csv", action="store_true")
        parser.add_argument("--review-min-risk", type=int, default=3)
        parser.add_argument("--review-high-only", action="store_true")
        parser.add_argument("--tf-count", type=int, default=60, help="Number of TF candidates to generate.")
        parser.add_argument("--false-ratio", type=float, default=0.5, help="Target ratio for FALSE items.")
        parser.add_argument("--seed", type=int, default=42)
        parser.add_argument(
            "--decision-domain",
            action="append",
            choices=list(ALLOWED_DECISION_DOMAINS),
            dest="decision_domains",
            default=None,
            help="Repeat to include multiple decision domains. Default: all domains.",
        )
        parser.add_argument("--min-stand-year", type=int, default=None)
        parser.add_argument("--max-stand-year", type=int, default=None)
        parser.add_argument(
            "--min-answer-chars",
            type=int,
            default=180,
            help="Minimum answer length required for FAQ item inclusion.",
        )

    def handle(self, *args, **options):
        split_subset = str(options["split_subset"])
        split_json = None if split_subset == "all" else Path(str(options["split_json"]))
        review_csv_path = None if bool(options.get("no_review_csv")) else Path(str(options["review_csv"]))

        config = FAQTestSetBuildConfig(
            faq_dataset_path=Path(str(options["faq_dataset"])),
            split_json_path=split_json,
            split_subset=split_subset,
            output_json_path=Path(str(options["output_json"])),
            output_markdown_path=Path(str(options["output_md"])),
            tf_count=int(options["tf_count"]),
            false_ratio=float(options["false_ratio"]),
            seed=int(options["seed"]),
            decision_domains=tuple(options.get("decision_domains") or ALLOWED_DECISION_DOMAINS),
            min_stand_year=options.get("min_stand_year"),
            max_stand_year=options.get("max_stand_year"),
            min_answer_chars=int(options["min_answer_chars"]),
            review_csv_path=review_csv_path,
            review_min_risk=int(options["review_min_risk"]),
            review_high_only=bool(options.get("review_high_only")),
        )

        try:
            result = build_test_set_from_faq(config)
        except RAGError as exc:
            raise CommandError(str(exc)) from exc

        self.stdout.write(self.style.SUCCESS("FAQ-based test-set candidate generation completed."))
        self.stdout.write(f"Output JSON: {result['output_json_path']}")
        self.stdout.write(f"Output MD: {result['output_markdown_path']}")
        if result.get("review_csv_path"):
            self.stdout.write(f"Review CSV: {result['review_csv_path']}")
            self.stdout.write(f"Review rows: {result.get('review_row_count', 0)}")
        self.stdout.write(f"FAQ items after filters: {result['faq_items_after_filter']}")
        self.stdout.write(f"TF generated: {result['tf_generated_count']}")
        self.stdout.write(f"TRUE/FALSE: {result['true_count']}/{result['false_count']}")
        self.stdout.write(f"Domain distribution: {result['domain_distribution']}")
